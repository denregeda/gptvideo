INSERT INTO media_folders (advertiser_id, name)
SELECT a.id, defaults.name
FROM advertisers a
CROSS JOIN (VALUES ('Видеореклама'), ('Документы')) AS defaults(name)
ON CONFLICT (advertiser_id, name) DO NOTHING;

